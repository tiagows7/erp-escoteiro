-- Famílias: vários associados no mesmo grupo para cobrança unificada.

create table if not exists public.familia (
  familia_id integer generated by default as identity primary key,
  empresa_id integer not null references public.empresa (id) on delete cascade,
  nome varchar(100) not null,
  responsavel_associado_id integer
    references public.associados (associado_id) on delete set null,
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists familia_empresa_nome_idx
  on public.familia (empresa_id, nome);

create index if not exists familia_responsavel_idx
  on public.familia (responsavel_associado_id);

alter table public.associados
  add column if not exists familia_id integer
    references public.familia (familia_id) on delete set null;

create index if not exists associados_familia_idx
  on public.associados (familia_id);

alter table public.receitas
  add column if not exists familia_id integer
    references public.familia (familia_id) on delete set null;

create index if not exists receitas_familia_idx
  on public.receitas (familia_id);

create unique index if not exists receitas_mensalidade_familia_uidx
  on public.receitas (empresa_id, familia_id, receita_competencia)
  where receita_origem = 'M'
    and familia_id is not null
    and receita_competencia is not null;

comment on table public.familia is
  'Grupo familiar de associados. A mensalidade pode ser gerada em um único título.';
comment on column public.associados.familia_id is
  'Família do associado. Quem tem família não gera mensalidade individual.';
comment on column public.receitas.familia_id is
  'Preenchido quando a mensalidade é o título único da família.';

alter table public.familia enable row level security;

select public.harden_tenant_write_policies('familia', 'can_write_empresa');
select public.auditoria_attach('familia', 'familia_id');

grant select, insert, update, delete on public.familia to authenticated;
grant usage, select on all sequences in schema public to authenticated;
