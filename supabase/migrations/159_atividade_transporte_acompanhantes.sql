-- Transporte na atividade: lista com jovens (nome/CPF) e familiares acompanhantes.

alter table public.atividades
  add column if not exists tem_transporte boolean not null default false;

comment on column public.atividades.tem_transporte is
  'Quando true, a confirmação coleta CPF e familiares para a lista de transporte.';

create table if not exists public.atividade_acompanhante (
  acompanhante_id integer generated by default as identity primary key,
  empresa_id integer not null references public.empresa (id),
  confirmacao_id integer not null
    references public.atividade_confirmacao (confirmacao_id) on delete cascade,
  atividade_id integer not null
    references public.atividades (atividade_id) on delete cascade,
  associado_id integer not null
    references public.associados (associado_id) on delete cascade,
  nome text not null,
  cpf varchar(15) not null,
  created_at timestamptz not null default now(),
  constraint atividade_acompanhante_nome_chk check (char_length(btrim(nome)) > 0),
  constraint atividade_acompanhante_cpf_chk check (char_length(btrim(cpf)) > 0)
);

create index if not exists atividade_acompanhante_atividade_idx
  on public.atividade_acompanhante (atividade_id);

create index if not exists atividade_acompanhante_confirmacao_idx
  on public.atividade_acompanhante (confirmacao_id);

create index if not exists atividade_acompanhante_associado_idx
  on public.atividade_acompanhante (associado_id);

alter table public.atividade_acompanhante enable row level security;

grant select, insert, update, delete on public.atividade_acompanhante to authenticated;
grant usage, select on all sequences in schema public to authenticated;

select public.harden_tenant_write_policies(
  'atividade_acompanhante',
  'can_write_empresa'
);

-- Confirma participação e grava/atualiza familiares (e CPF do jovem, se informado).
drop function if exists public.atividade_confirmar_participacao(integer);
drop function if exists public.atividade_confirmar_participacao(integer, text, jsonb);

create or replace function public.atividade_confirmar_participacao(
  p_atividade_id integer,
  p_cpf text default null,
  p_acompanhantes jsonb default '[]'::jsonb
)
returns table (
  ok boolean,
  mensagem text,
  confirmacao_id integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_atividade public.atividades%rowtype;
  v_assoc public.associados%rowtype;
  v_assoc_id integer;
  v_id integer;
  v_cpf text;
  v_item jsonb;
  v_nome text;
  v_acomp_cpf text;
begin
  if auth.uid() is null then
    return query select false, 'Não autenticado.'::text, null::integer;
    return;
  end if;

  select * into v_atividade
  from public.atividades a
  where a.atividade_id = p_atividade_id;

  if not found then
    return query select false, 'Atividade não encontrada.'::text, null::integer;
    return;
  end if;

  if not public.can_access_empresa(v_atividade.empresa_id) then
    return query select false, 'Sem acesso a este grupo.'::text, null::integer;
    return;
  end if;

  v_assoc_id := public.atividade_associado_do_usuario();
  if v_assoc_id is null then
    return query
      select false, 'Associado não encontrado para o seu registro.'::text, null::integer;
    return;
  end if;

  select * into v_assoc
  from public.associados a
  where a.associado_id = v_assoc_id
    and a.empresa_id = v_atividade.empresa_id;

  if not found then
    return query select false, 'Associado inválido para esta atividade.'::text, null::integer;
    return;
  end if;

  if not (v_atividade.ramo is null and v_atividade.secao is null) then
    if v_atividade.ramo is not null
       and (v_assoc.ramo is null or v_atividade.ramo <> v_assoc.ramo) then
      return query
        select false, 'Esta atividade não está disponível para você.'::text, null::integer;
      return;
    end if;
    if v_atividade.secao is not null
       and (v_assoc.secao is null or v_atividade.secao <> v_assoc.secao) then
      return query
        select false, 'Esta atividade não está disponível para você.'::text, null::integer;
      return;
    end if;
    if v_atividade.patrulha_matilha is not null
       and (
         v_assoc.patrulha_matilha is null
         or v_atividade.patrulha_matilha <> v_assoc.patrulha_matilha
       ) then
      return query
        select false, 'Esta atividade não está disponível para você.'::text, null::integer;
      return;
    end if;
  end if;

  v_cpf := nullif(regexp_replace(coalesce(p_cpf, ''), '\D', '', 'g'), '');
  if v_cpf is null then
    v_cpf := nullif(regexp_replace(coalesce(v_assoc.cpf, ''), '\D', '', 'g'), '');
  end if;

  if coalesce(v_atividade.tem_transporte, false)
     and (v_cpf is null or char_length(v_cpf) < 11) then
    return query
      select false,
        'Informe o seu CPF (11 dígitos) para a lista de transporte.'::text,
        null::integer;
    return;
  end if;

  if v_cpf is not null then
    if char_length(v_cpf) < 11 then
      return query select false, 'Informe um CPF válido com 11 dígitos.'::text, null::integer;
      return;
    end if;
    update public.associados a
       set cpf = left(v_cpf, 15)
     where a.associado_id = v_assoc.associado_id
       and a.empresa_id = v_atividade.empresa_id;
  end if;

  select c.confirmacao_id into v_id
  from public.atividade_confirmacao c
  where c.atividade_id = v_atividade.atividade_id
    and c.associado_id = v_assoc.associado_id;

  if v_id is null then
    insert into public.atividade_confirmacao (
      empresa_id,
      atividade_id,
      associado_id
    ) values (
      v_atividade.empresa_id,
      v_atividade.atividade_id,
      v_assoc.associado_id
    )
    returning atividade_confirmacao.confirmacao_id into v_id;
  end if;

  if coalesce(v_atividade.tem_transporte, false) then
    if p_acompanhantes is null or jsonb_typeof(p_acompanhantes) <> 'array' then
      return query select false, 'Lista de acompanhantes inválida.'::text, v_id;
      return;
    end if;

    for v_item in
      select value from jsonb_array_elements(p_acompanhantes)
    loop
      v_nome := nullif(btrim(coalesce(v_item->>'nome', '')), '');
      v_acomp_cpf := nullif(
        regexp_replace(coalesce(v_item->>'cpf', ''), '\D', '', 'g'),
        ''
      );
      if v_nome is null and v_acomp_cpf is null then
        continue;
      end if;
      if v_nome is null then
        return query
          select false, 'Informe o nome de cada pessoa da família.'::text, v_id;
        return;
      end if;
      if v_acomp_cpf is null or char_length(v_acomp_cpf) < 11 then
        return query
          select false,
            'Informe o CPF (11 dígitos) de cada pessoa da família.'::text,
            v_id;
        return;
      end if;
    end loop;

    delete from public.atividade_acompanhante a
    where a.confirmacao_id = v_id
      and a.empresa_id = v_atividade.empresa_id;

    insert into public.atividade_acompanhante (
      empresa_id,
      confirmacao_id,
      atividade_id,
      associado_id,
      nome,
      cpf
    )
    select
      v_atividade.empresa_id,
      v_id,
      v_atividade.atividade_id,
      v_assoc.associado_id,
      btrim(v.value->>'nome'),
      left(regexp_replace(coalesce(v.value->>'cpf', ''), '\D', '', 'g'), 15)
    from jsonb_array_elements(p_acompanhantes) as v(value)
    where nullif(btrim(coalesce(v.value->>'nome', '')), '') is not null
      and nullif(
        regexp_replace(coalesce(v.value->>'cpf', ''), '\D', '', 'g'),
        ''
      ) is not null;
  end if;

  return query select true, 'Participação confirmada.'::text, v_id;
end;
$$;

revoke all on function public.atividade_confirmar_participacao(integer, text, jsonb) from public;
grant execute on function public.atividade_confirmar_participacao(integer, text, jsonb) to authenticated;

-- Lista de transporte: jovens confirmados + familiares.
create or replace function public.atividade_lista_transporte(
  p_atividade_id integer
)
returns table (
  tipo text,
  associado_id integer,
  nome text,
  cpf text,
  confirmacao_id integer
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_atividade public.atividades%rowtype;
begin
  if auth.uid() is null then
    return;
  end if;

  select * into v_atividade
  from public.atividades a
  where a.atividade_id = p_atividade_id;

  if not found then
    return;
  end if;

  if not public.can_access_empresa(v_atividade.empresa_id) then
    return;
  end if;

  if not coalesce(v_atividade.tem_transporte, false) then
    return;
  end if;

  return query
  select * from (
    select
      'jovem'::text as tipo,
      a.associado_id,
      a.nome::text as nome,
      coalesce(a.cpf, '')::text as cpf,
      c.confirmacao_id
    from public.atividade_confirmacao c
    join public.associados a
      on a.associado_id = c.associado_id
     and a.empresa_id = c.empresa_id
    where c.atividade_id = v_atividade.atividade_id
      and c.empresa_id = v_atividade.empresa_id
    union all
    select
      'acompanhante'::text,
      ac.associado_id,
      ac.nome::text,
      ac.cpf::text,
      ac.confirmacao_id
    from public.atividade_acompanhante ac
    where ac.atividade_id = v_atividade.atividade_id
      and ac.empresa_id = v_atividade.empresa_id
  ) lista
  order by
    case when lista.tipo = 'jovem' then 0 else 1 end,
    lista.nome;
end;
$$;

revoke all on function public.atividade_lista_transporte(integer) from public;
grant execute on function public.atividade_lista_transporte(integer) to authenticated;
