-- Acerto de saldo inicial do Portal da Transparência.
-- Usado ao iniciar um grupo novo ou alinhar o caixa de grupo já em andamento.

create table if not exists public.portal_saldo_acerto (
  id bigint generated by default as identity primary key,
  empresa_id integer not null references public.empresa (id) on delete cascade,
  -- 0 = caixa do grupo; 1..4 = ramos (não usa -1/geral)
  caixa_id integer not null
    check (caixa_id >= 0 and caixa_id <= 4),
  secao_id integer null references public.secao (secao_id) on delete set null,
  -- Vale como saldo inicial nos períodos com periodo_inicio >= data_acerto
  -- (regra: data_acerto <= periodo_inicio).
  data_acerto date not null,
  valor numeric(15, 2) not null,
  observacao text null,
  created_by uuid null references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists portal_saldo_acerto_empresa_idx
  on public.portal_saldo_acerto (empresa_id, data_acerto, caixa_id);

comment on table public.portal_saldo_acerto is
  'Ajustes de saldo inicial do Portal da Transparência por caixa/seção.';

comment on column public.portal_saldo_acerto.data_acerto is
  'Data de referência: entra no saldo inicial dos períodos com início nesta data ou depois.';

alter table public.portal_saldo_acerto enable row level security;

drop policy if exists "portal_saldo_acerto_select" on public.portal_saldo_acerto;
create policy "portal_saldo_acerto_select"
  on public.portal_saldo_acerto
  for select
  to authenticated
  using (public.can_access_empresa(empresa_id));

drop policy if exists "portal_saldo_acerto_write" on public.portal_saldo_acerto;
create policy "portal_saldo_acerto_write"
  on public.portal_saldo_acerto
  for all
  to authenticated
  using (public.can_access_empresa(empresa_id))
  with check (public.can_access_empresa(empresa_id));

grant select, insert, update, delete on public.portal_saldo_acerto to authenticated;
grant all on table public.portal_saldo_acerto to service_role;

do $$
begin
  perform public.auditoria_attach('portal_saldo_acerto', 'id');
exception
  when undefined_function then
    null;
  when others then
    null;
end;
$$;

drop trigger if exists portal_totais_inv_saldo_acerto on public.portal_saldo_acerto;
create trigger portal_totais_inv_saldo_acerto
  after insert or update or delete on public.portal_saldo_acerto
  for each row execute function public.portal_totais_invalidate_trigger();

-- Inclui acertos no cálculo do saldo inicial.
create or replace function public.portal_totais_gerar(
  p_empresa_id integer,
  p_ano integer,
  p_mes integer default 0,
  p_caixa integer default -1,
  p_secao integer default 0
)
returns public.portal_totais
language plpgsql
security definer
set search_path = public
as $$
declare
  v_mes integer := coalesce(p_mes, 0);
  v_caixa integer := coalesce(p_caixa, -1);
  v_secao integer := coalesce(p_secao, 0);
  v_periodo_inicio date;
  v_periodo_fim date;
  v_d_ant_pago numeric := 0;
  v_r_ant_recebido numeric := 0;
  v_d_pago numeric := 0;
  v_r_recebido numeric := 0;
  v_atraso numeric := 0;
  v_loc_resgatado numeric := 0;
  v_loc_aplicado numeric := 0;
  v_acerto numeric := 0;
  v_saldo_inicial numeric := 0;
  v_saldo_final numeric := 0;
  v_row public.portal_totais;
begin
  if p_empresa_id is null or p_ano is null then
    raise exception 'empresa_id e ano são obrigatórios';
  end if;
  if v_mes < 0 or v_mes > 12 then
    raise exception 'mês inválido';
  end if;

  if v_mes = 0 then
    v_periodo_inicio := make_date(p_ano, 1, 1);
    v_periodo_fim := make_date(p_ano + 1, 1, 1);
  else
    v_periodo_inicio := make_date(p_ano, v_mes, 1);
    v_periodo_fim :=
      case
        when v_mes = 12 then make_date(p_ano + 1, 1, 1)
        else make_date(p_ano, v_mes + 1, 1)
      end;
  end if;

  select
    coalesce(sum(despesa_valor - despesa_saldo), 0)::numeric
  into v_d_ant_pago
  from public.despesas
  where empresa_id = p_empresa_id
    and (
      v_caixa = -1
      or public._portal_caixa_id(despesa_ramo) = v_caixa
    )
    and (
      v_secao = 0
      or despesa_secao = v_secao
    )
    and despesa_emissao is not null
    and despesa_emissao < v_periodo_inicio;

  select
    coalesce(sum(receita_valor - receita_saldo), 0)::numeric
  into v_r_ant_recebido
  from public.receitas
  where empresa_id = p_empresa_id
    and (
      v_caixa = -1
      or public._portal_caixa_id(receita_ramo) = v_caixa
    )
    and (
      v_secao = 0
      or receita_secao = v_secao
    )
    and coalesce(receita_emissao, receita_competencia) is not null
    and coalesce(receita_emissao, receita_competencia) < v_periodo_inicio;

  select
    coalesce(sum(despesa_valor - despesa_saldo), 0)::numeric
  into v_d_pago
  from public.despesas
  where empresa_id = p_empresa_id
    and (
      v_caixa = -1
      or public._portal_caixa_id(despesa_ramo) = v_caixa
    )
    and (
      v_secao = 0
      or despesa_secao = v_secao
    )
    and despesa_emissao >= v_periodo_inicio
    and despesa_emissao < v_periodo_fim;

  select
    coalesce(sum(receita_valor - receita_saldo), 0)::numeric
  into v_r_recebido
  from public.receitas
  where empresa_id = p_empresa_id
    and (
      v_caixa = -1
      or public._portal_caixa_id(receita_ramo) = v_caixa
    )
    and (
      v_secao = 0
      or receita_secao = v_secao
    )
    and coalesce(receita_emissao, receita_competencia) >= v_periodo_inicio
    and coalesce(receita_emissao, receita_competencia) < v_periodo_fim;

  select coalesce(sum(rec.receita_saldo), 0)::numeric
  into v_atraso
  from public.receitas rec
  left join public.associados assoc on assoc.associado_id = rec.associado_id
  where rec.empresa_id = p_empresa_id
    and rec.receita_origem = 'M'
    and coalesce(rec.receita_saldo, 0) > 0
    and rec.receita_vencimento is not null
    and rec.receita_vencimento < current_date
    and (
      v_caixa = -1
      or v_caixa = 0
      or (
        v_caixa between 1 and 4
        and assoc.ramo = v_caixa
      )
    )
    and (
      v_secao = 0
      or assoc.secao = v_secao
    );

  select
    coalesce(sum(m.valor_resgatado), 0)::numeric,
    coalesce(sum(m.valor_aplicado), 0)::numeric
  into v_loc_resgatado, v_loc_aplicado
  from public.empresa_saldo_local_movimento m
  join public.empresa_saldo_local l
    on l.id = m.local_id
   and l.empresa_id = m.empresa_id
  where l.empresa_id = p_empresa_id
    and l.ativo = true
    and m.data_movimento < v_periodo_inicio
    and (
      v_caixa = -1
      or l.caixa_id = v_caixa
    )
    and (
      v_secao = 0
      or l.secao_id is null
      or l.secao_id = v_secao
    );

  select coalesce(sum(a.valor), 0)::numeric
  into v_acerto
  from public.portal_saldo_acerto a
  where a.empresa_id = p_empresa_id
    and a.data_acerto <= v_periodo_inicio
    and (
      v_caixa = -1
      or a.caixa_id = v_caixa
    )
    and (
      v_secao = 0
      or a.secao_id is null
      or a.secao_id = v_secao
    );

  v_saldo_inicial :=
    v_r_ant_recebido - v_d_ant_pago
    + v_loc_resgatado - v_loc_aplicado
    + v_acerto;
  v_saldo_final := v_saldo_inicial + v_r_recebido - v_d_pago;

  insert into public.portal_totais as t (
    empresa_id,
    ano,
    mes,
    caixa_id,
    secao_id,
    saldo_inicial,
    total_receitas,
    total_despesas,
    saldo_final,
    despesas_pagas,
    receitas_recebidas,
    saldo_lancado,
    saldo_realizado,
    mensalidades_atraso,
    atualizado_em
  )
  values (
    p_empresa_id,
    p_ano,
    v_mes,
    v_caixa,
    v_secao,
    v_saldo_inicial,
    v_r_recebido,
    v_d_pago,
    v_saldo_final,
    v_d_pago,
    v_r_recebido,
    (v_r_recebido - v_d_pago),
    (v_r_recebido - v_d_pago),
    v_atraso,
    now()
  )
  on conflict (empresa_id, ano, mes, caixa_id, secao_id) do update
  set
    saldo_inicial = excluded.saldo_inicial,
    total_receitas = excluded.total_receitas,
    total_despesas = excluded.total_despesas,
    saldo_final = excluded.saldo_final,
    despesas_pagas = excluded.despesas_pagas,
    receitas_recebidas = excluded.receitas_recebidas,
    saldo_lancado = excluded.saldo_lancado,
    saldo_realizado = excluded.saldo_realizado,
    mensalidades_atraso = excluded.mensalidades_atraso,
    atualizado_em = excluded.atualizado_em
  returning * into v_row;

  return v_row;
end;
$$;
